import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import scipy.stats as st
import statsmodels.api as sm

# ------------------------------------------------------------
# Исходные данные (20 наблюдений)
# ------------------------------------------------------------
t = np.arange(1, 21)
x = np.array([14, 16, 17, 19, 18, 15, 14, 18, 17, 15,
              13, 16, 17, 19, 18, 20, 12, 13, 12, 14])
y = np.array([222, 241, 243, 285, 253, 247, 246, 276, 261, 254,
              229, 249, 252, 279, 262, 275, 211, 222, 218, 232])

T = len(x)
print(f'Объём выборки T = {T}')

# ------------------------------------------------------------
# 2. Точечный график зависимости y от x
# ------------------------------------------------------------
plt.figure(figsize=(8, 5))
plt.scatter(x, y, color='blue', label='Исходные данные')
plt.xlabel('x')
plt.ylabel('y')
plt.title('Диаграмма рассеяния y от x')
plt.ylim(200, 300)   # по заданию масштаб Y от 200 до 300
plt.xlim(12, 20)     # масштаб X от 12 до 20
plt.grid(True)
plt.legend()
plt.show()

# ------------------------------------------------------------
# 3. Предварительная оценка коэффициентов по графику
#    (визуально: линия восходит -> a1 > 0; пересечение с осью Y ~ 50-100)
# ------------------------------------------------------------
print('\n3. Предварительная оценка:')
print('   По графику: a1 > 0 (положительный наклон), a0 < 200 (отрицательное пересечение?)')
print('   При x=0 значение y было бы меньше 0, но масштаб не позволяет оценить точно.')

# ------------------------------------------------------------
# 4. Расчётная таблица с необходимыми столбцами
# ------------------------------------------------------------
x_mean = np.mean(x)
y_mean = np.mean(y)
x_sq_mean = np.mean(x**2)

# Создаём DataFrame для удобства
df = pd.DataFrame({
    't': t,
    'x_t': x,
    'y_t': y,
    'x_t^2': x**2,
    'x_t - x̄': x - x_mean,
    '(x_t - x̄)^2': (x - x_mean)**2,
    'y_t - ȳ': y - y_mean,
    '(y_t - ȳ)^2': (y - y_mean)**2,
    '(x_t - x̄)(y_t - ȳ)': (x - x_mean) * (y - y_mean)
})

# Вывод таблицы на экран
print('\n4. Расчётная таблица:')
print(df.round(2).to_string(index=False))

# Суммы и средние
sums = df[['x_t^2', '(x_t - x̄)^2', '(y_t - ȳ)^2', '(x_t - x̄)(y_t - ȳ)']].sum()
print('\nСуммы:')
print(sums)
print(f'Среднее x̄ = {x_mean:.4f}, Среднее ȳ = {y_mean:.4f}')
print(f'Среднее квадратов x² = {x_sq_mean:.4f}')

# ------------------------------------------------------------
# 5. Расчёт коэффициентов a1 и a0 методом МНК
# ------------------------------------------------------------
a1 = sums['(x_t - x̄)(y_t - ȳ)'] / sums['(x_t - x̄)^2']
a0 = y_mean - a1 * x_mean

print(f'\n5. Коэффициенты модели:')
print(f'   a1 = {a1:.4f}')
print(f'   a0 = {a0:.4f}')

# ------------------------------------------------------------
# 6. Прогнозные значения, ошибки и слагаемые дисперсии
# ------------------------------------------------------------
df['ŷ_t'] = a0 + a1 * x
df['e_t'] = y - df['ŷ_t']
df['e_t^2'] = df['e_t'] ** 2
df['s_t^2'] = df['e_t^2'] / (T - 2)

print('\n6. Таблица с прогнозами и ошибками:')
print(df[['t', 'x_t', 'y_t', 'ŷ_t', 'e_t', 'e_t^2', 's_t^2']].round(4).to_string(index=False))

# ------------------------------------------------------------
# 7. Несмещённая оценка дисперсии случайных переменных (s^2)
# ------------------------------------------------------------
s2 = df['s_t^2'].sum()                # сумма s_t^2 = Σ e_t^2/(T-2) = (1/(T-2)) Σ e_t^2
s2_direct = df['e_t^2'].sum() / (T - 2)
print(f'\n7. Несмещённая оценка дисперсии s² = {s2:.4f} (прямой расчёт: {s2_direct:.4f})')

# ------------------------------------------------------------
# 8. Несмещённая оценка дисперсии a1
# ------------------------------------------------------------
# Формула: s²_{a1} = s² / (T * (x² - (x̄)²))
s2_a1 = s2 / (T * (x_sq_mean - x_mean**2))
# Альтернативно: s²_{a1} = s² / Σ(x_t - x̄)²
s2_a1_alt = s2 / sums['(x_t - x̄)^2']
s_a1 = np.sqrt(s2_a1)

print(f'\n8. Дисперсия a1: s²_{a1} = {s2_a1:.4f} (альтернативно {s2_a1_alt:.4f})')
print(f'   Стандартная ошибка a1: s_{a1} = {s_a1:.4f}')

# ------------------------------------------------------------
# 9. Несмещённая оценка дисперсии a0
# ------------------------------------------------------------
# Классическая формула: Var(a0) = s² * (1/T + x̄² / Σ(x_t - x̄)²)
s2_a0 = s2 * (1/T + x_mean**2 / sums['(x_t - x̄)^2'])
s_a0 = np.sqrt(s2_a0)

print(f'\n9. Дисперсия a0: s²_{a0} = {s2_a0:.4f}')
print(f'   Стандартная ошибка a0: s_{a0} = {s_a0:.4f}')

# ------------------------------------------------------------
# 10. Квантили распределения Стьюдента
# ------------------------------------------------------------
gammas = [0.90, 0.95, 0.99]
t_crit = {}
for gamma in gammas:
    # двусторонний квантиль: t_{1 - (1-gamma)/2, T-2}
    t_val = st.t.ppf(1 - (1 - gamma) / 2, T - 2)
    t_crit[gamma] = t_val
    print(f'\n10. t(γ={gamma}, df={T-2}) = {t_val:.4f}')

# ------------------------------------------------------------
# 11. t-статистика для a1 и проверка значимости
# ------------------------------------------------------------
t_a1 = a1 / s_a1
print(f'\n11. Наблюдаемое t_a1 = {t_a1:.4f}')
for gamma, t_val in t_crit.items():
    if abs(t_a1) > t_val:
        print(f'   Для γ={gamma}: |t_a1| > t_крит, параметр a1 значим.')
    else:
        print(f'   Для γ={gamma}: |t_a1| <= t_крит, параметр a1 не значим.')

# ------------------------------------------------------------
# 12. t-статистика для a0 и проверка значимости
# ------------------------------------------------------------
t_a0 = a0 / s_a0
print(f'\n12. Наблюдаемое t_a0 = {t_a0:.4f}')
for gamma, t_val in t_crit.items():
    if abs(t_a0) > t_val:
        print(f'   Для γ={gamma}: |t_a0| > t_крит, параметр a0 значим.')
    else:
        print(f'   Для γ={gamma}: |t_a0| <= t_крит, параметр a0 не значим.')

# ------------------------------------------------------------
# 13. Доверительные интервалы для a1
# ------------------------------------------------------------
print('\n13. Доверительные интервалы для a1:')
for gamma, t_val in t_crit.items():
    lower = a1 - t_val * s_a1
    upper = a1 + t_val * s_a1
    print(f'   γ={gamma}: ({lower:.4f}, {upper:.4f})')

# ------------------------------------------------------------
# 14. Доверительные интервалы для a0
# ------------------------------------------------------------
print('\n14. Доверительные интервалы для a0:')
for gamma, t_val in t_crit.items():
    lower = a0 - t_val * s_a0
    upper = a0 + t_val * s_a0
    print(f'   γ={gamma}: ({lower:.4f}, {upper:.4f})')

# ------------------------------------------------------------
# 15. Коэффициент детерминации R²
# ------------------------------------------------------------
SS_res = df['e_t^2'].sum()
SS_tot = sums['(y_t - ȳ)^2']
R2 = 1 - SS_res / SS_tot
print(f'\n15. Коэффициент детерминации R² = {R2:.4f}')
if R2 > 0.8:
    print('   Модель объясняет более 80% вариации – предварительно адекватна.')
else:
    print('   Модель может быть недостаточно адекватной.')

# ------------------------------------------------------------
# 16. Квантили распределения Фишера
# ------------------------------------------------------------

f_crit = {}
for gamma in gammas:
    f_val = st.f.ppf(gamma, 1, T - 2)
    f_crit[gamma] = f_val
    print(f'\n16. F(γ={gamma}, df1=1, df2={T-2}) = {f_val:.4f}')

# ------------------------------------------------------------
# 17. F-статистика и проверка значимости R²
# ------------------------------------------------------------
F_stat = (R2 / (1 - R2)) * (T - 2)  # df1=1
print(f'\n17. Наблюдаемое F = {F_stat:.4f}')
for gamma, f_val in f_crit.items():
    if F_stat > f_val:
        print(f'   Для γ={gamma}: F > F_крит, коэффициент детерминации R² значим.')
    else:
        print(f'   Для γ={gamma}: F <= F_крит, R² не значим.')

# ------------------------------------------------------------
# 18. Прогнозы для x от 12 до 20
# ------------------------------------------------------------
x_pred = np.arange(12, 21)
y_pred = a0 + a1 * x_pred

print('\n18. Прогнозные значения:')
for xp, yp in zip(x_pred, y_pred):
    print(f'   x = {xp:2d} -> y_пр = {yp:.2f}')

# ------------------------------------------------------------
# 19. Доверительные интервалы для индивидуального прогноза
# ------------------------------------------------------------
# Формула: y_пр ± t_{γ,T-2} * s * sqrt(1 + (x_пр - x̄)² / Σ(x_t - x̄)²)
s = np.sqrt(s2)
Sxx = sums['(x_t - x̄)^2']

print('\n19. Доверительные интервалы для прогнозов:')
for gamma, t_val in t_crit.items():
    print(f'\n   Уровень γ={gamma}:')
    for xp, yp in zip(x_pred, y_pred):
        se = s * np.sqrt(1 + (xp - x_mean)**2 / Sxx)
        lower = yp - t_val * se
        upper = yp + t_val * se
        print(f'   x = {xp:2d}: {yp:.2f} ± {t_val*se:.2f}  => ({lower:.2f}, {upper:.2f})')

# ------------------------------------------------------------
# 20. Графики прогнозов с доверительными полосами
# ------------------------------------------------------------
x_plot = np.linspace(12, 20, 100)
y_plot = a0 + a1 * x_plot

plt.figure(figsize=(10, 6))
plt.scatter(x, y, color='blue', label='Исходные данные')
plt.plot(x_plot, y_plot, 'k-', label='Линия регрессии')

for gamma, t_val in t_crit.items():
    se_plot = s * np.sqrt(1 + (x_plot - x_mean)**2 / Sxx)
    lower_band = y_plot - t_val * se_plot
    upper_band = y_plot + t_val * se_plot
    plt.fill_between(x_plot, lower_band, upper_band, alpha=0.15,
                     label=f'Дов. интервал γ={gamma}')

plt.ylim(190, 310)
plt.xlim(12, 20)
plt.xlabel('x')
plt.ylabel('y')
plt.title('Прогноз и доверительные интервалы')
plt.legend()
plt.grid(True)
plt.show()

# ------------------------------------------------------------
# 21. График остатков
# ------------------------------------------------------------
plt.figure(figsize=(8, 5))
plt.scatter(df['x_t'], df['e_t'], color='red')
plt.axhline(0, color='black', linestyle='--')
plt.xlabel('x')
plt.ylabel('Остатки e_t')
plt.title('График остатков')
plt.grid(True)
plt.show()

print('\n21. Анализ остатков: на графике нет явных закономерностей, '
      'что позволяет предположить выполнение предпосылок МНК (гомоскедастичность, отсутствие автокорреляции).')

# ------------------------------------------------------------
# Часть II. Оценка модели с помощью statsmodels (аналог EViews)
# ------------------------------------------------------------
# Добавляем константу для a0
X = sm.add_constant(x)  # первый столбец — единицы
model = sm.OLS(y, X)
results = model.fit()

print("\n" + "="*60)
print("РЕЗУЛЬТАТЫ ОЦЕНКИ МОДЕЛИ (statsmodels)")
print("="*60)
print(results.summary())